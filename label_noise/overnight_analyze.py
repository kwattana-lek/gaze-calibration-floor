#!/usr/bin/env python
"""Overnight batch analyzer -> logs/MONDAY_REPORT.md (new tooling; reads outputs
only, modifies no experiment code). Produces the 7 requested report items.
Every section is guarded so a failed/missing step degrades to a note."""
import json, os, glob
import numpy as np

AG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LN = os.path.join(AG, 'label_noise')
LOGS = os.path.join(AG, 'logs')
RNG = np.random.RandomState(0)
B = 2000  # bootstrap resamples


def load_jsonl(p):
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else None


def roc_auc(scores, pos):
    scores = np.asarray(scores, float); pos = np.asarray(pos, bool)
    ok = ~np.isnan(scores); scores, pos = scores[ok], pos[ok]
    npos, nneg = int(pos.sum()), int((~pos).sum())
    if npos == 0 or nneg == 0:
        return float('nan')
    u, inv, cnt = np.unique(scores, return_inverse=True, return_counts=True)
    csum = np.cumsum(cnt); avg = (csum - cnt + csum + 1) / 2.0
    return float((avg[inv][pos].sum() - npos * (npos + 1) / 2) / (npos * nneg))


def boot_ci(scores, pos, B=B):
    scores = np.asarray(scores, float); pos = np.asarray(pos, bool)
    n = len(scores); aucs = []
    for _ in range(B):
        idx = RNG.randint(0, n, n)
        a = roc_auc(scores[idx], pos[idx])
        if not np.isnan(a):
            aucs.append(a)
    if not aucs:
        return (float('nan'), float('nan'))
    return (float(np.percentile(aucs, 2.5)), float(np.percentile(aucs, 97.5)))


def cell_records(recs, model, delta, pc):
    y, loo, src = [], [], []
    for r in recs:
        if r['model'] == model and r['delta'] == delta and abs(r['pc'] - pc) < 1e-9:
            y.append(r['is_corrupted'])
            loo.append(np.nan if r['loo_residual_deg'] is None else r['loo_residual_deg'])
            src.append(np.nan if r['source_residual_deg'] is None else r['source_residual_deg'])
    return np.array(y, bool), np.array(loo, float), np.array(src, float)


def crossing(deltas, aucs, level):
    """Smallest delta where auc(delta) crosses `level` going up (linear interp)."""
    d = np.array(deltas, float); a = np.array(aucs, float)
    order = np.argsort(d); d, a = d[order], a[order]
    if np.all(a < level):
        return f">{d.max():.0f}"
    if a[0] >= level:
        return f"<={d.min():.0f}"
    for i in range(1, len(d)):
        if a[i - 1] < level <= a[i]:
            t = (level - a[i - 1]) / (a[i] - a[i - 1])
            return round(float(d[i - 1] + t * (d[i] - d[i - 1])), 2)
    return "n/a"


def sec_to_hms(s):
    s = int(s); return f"{s//3600}h{(s%3600)//60:02d}m{s%60:02d}s"


L = []
def w(*x): L.append(" ".join(str(t) for t in x))

w("# Overnight batch — Monday report")
w("")
w("Generated by `label_noise/overnight_analyze.py`. Env: `~/miniconda3/envs/agentgaze/bin/python`. "
  "No experiment code was modified.")
w("")

# ---- item 1: Step 1 verdict ----
w("## 1. Step 1 — CPU vs MPS agreement (gate)")
vf = os.path.join(LOGS, 'step1_verdict.txt')
if os.path.exists(vf):
    w("```"); w(open(vf).read().strip()); w("```")
else:
    w("_Step 1 verdict file missing — gate did not run._")
w("")

# ---- items 2/3/4: floor sweep ----
floor = load_jsonl(os.path.join(LN, 'phase1_records_floor.jsonl')) \
    or load_jsonl(os.path.join(LN, 'phase1_records.jsonl'))
w("## 2. Floor sweep — AUC by delta and pc (LOO & source), 95% bootstrap CI, corrupted counts")
if not floor:
    w("_Floor records missing._")
else:
    deltas = sorted({r['delta'] for r in floor if r['model'] == 'random_offset' and r['delta'] is not None})
    pcs = sorted({r['pc'] for r in floor})
    w(f"Data: {len(floor)} frame records; subjects/seeds aggregated per cell. "
      f"deltas={deltas} pcs={pcs}. Bootstrap B={B}.")
    w("")
    w("| model | δ | pc | n | corrupted | AUC_loo [95% CI] | AUC_src [95% CI] |")
    w("|---|---|---|---|---|---|---|")
    loo_by_pc = {pc: {} for pc in pcs}; src_by_pc = {pc: {} for pc in pcs}
    for pc in pcs:
        for d in deltas:
            y, loo, src = cell_records(floor, 'random_offset', d, pc)
            al, ci_l = roc_auc(loo, y), boot_ci(loo, y)
            asrc, ci_s = roc_auc(src, y), boot_ci(src, y)
            loo_by_pc[pc][d] = al; src_by_pc[pc][d] = asrc
            w(f"| random_offset | {d} | {pc} | {len(y)} | {int(y.sum())} | "
              f"{al:.3f} [{ci_l[0]:.3f}, {ci_l[1]:.3f}] | {asrc:.3f} [{ci_s[0]:.3f}, {ci_s[1]:.3f}] |")
        # structured (delta=None) for this pc
        ys, loos, srcs = cell_records(floor, 'structured_swap', None, pc)
        al, ci_l = roc_auc(loos, ys), boot_ci(loos, ys)
        asrc, ci_s = roc_auc(srcs, ys), boot_ci(srcs, ys)
        w(f"| structured_swap | – | {pc} | {len(ys)} | {int(ys.sum())} | "
          f"{al:.3f} [{ci_l[0]:.3f}, {ci_l[1]:.3f}] | {asrc:.3f} [{ci_s[0]:.3f}, {ci_s[1]:.3f}] |")
    w("")
    # ---- item 3: crossings ----
    w("## 3. δ at which AUC_loo crosses 0.7 and 0.9, per contamination rate")
    w("| pc | δ@AUC=0.7 (loo) | δ@AUC=0.9 (loo) | δ@0.7 (src) | δ@0.9 (src) |")
    w("|---|---|---|---|---|")
    cross07 = {}
    for pc in pcs:
        dl = sorted(loo_by_pc[pc]); la = [loo_by_pc[pc][d] for d in dl]
        sa = [src_by_pc[pc][d] for d in dl]
        c07 = crossing(dl, la, 0.7); c09 = crossing(dl, la, 0.9)
        cross07[pc] = c07
        w(f"| {pc} | {c07} | {c09} | {crossing(dl, sa, 0.7)} | {crossing(dl, sa, 0.9)} |")
    w("")
    w("_Note: floor covers δ∈{3,4,5,6}; a crossing shown as `>6` lies beyond the swept range._")
    w("")
    # ---- item 4: structured offsets ----
    w("## 4. Structured-swap realised offsets — percentiles & fraction below crossing")
    all_off = np.array([r['actual_offset_deg'] for r in floor
                        if r['model'] == 'structured_swap' and r['is_corrupted']], float)
    if all_off.size:
        pcts = [5, 10, 25, 50, 75, 90, 95]
        w("Realised angular offset of corrupted structured (donor-swap) frames, all pc pooled:")
        w("")
        w("| percentile | " + " | ".join(f"p{p}" for p in pcts) + " |")
        w("|---|" + "---|" * len(pcts))
        w("| deg | " + " | ".join(f"{np.percentile(all_off, p):.2f}" for p in pcts) + " |")
        w("")
        w("Fraction of realised structured offsets **below the δ@AUC=0.7 crossing** (i.e. in the "
          "undetectable regime), per pc:")
        w("")
        w("| pc | crossing δ@0.7 | structured offsets < crossing |")
        w("|---|---|---|")
        for pc in pcs:
            off_pc = np.array([r['actual_offset_deg'] for r in floor
                               if r['model'] == 'structured_swap' and r['is_corrupted']
                               and abs(r['pc'] - pc) < 1e-9], float)
            c = cross07[pc]
            if isinstance(c, (int, float)):
                frac = float((off_pc < c).mean()) if off_pc.size else float('nan')
                w(f"| {pc} | {c} | {frac*100:.1f}%  ({int((off_pc<c).sum())}/{off_pc.size}) |")
            else:
                w(f"| {pc} | {c} | n/a (crossing outside swept range) |")
    else:
        w("_No structured corrupted frames found._")
w("")

# ---- item 5: backbone reproduction ----
w("## 5. Backbone-fold MAE reproduction (Step 3)")
recorded = os.path.join(AG, 'experiments', 'lopo_backbone', 'results_recorded_ref.json')
newp = os.path.join(AG, 'experiments', 'lopo_backbone', 'results_overnight_20260808.json')
if not os.path.exists(recorded):
    recorded = os.path.join(AG, '_backups', 'models_20260808', 'lopo_backbone_results_recorded.json')
if os.path.exists(recorded) and os.path.exists(newp):
    rec = {r['subject']: r for r in json.load(open(recorded))}
    new = {r['subject']: r for r in json.load(open(newp))}
    w("Tolerance for 'reproduced' = |Δ| ≤ 0.05 deg (MPS float nondeterminism; seed 0).")
    w("")
    w("| subject | recorded cross | new cross | Δ | recorded full(K=9) | new full | Δ | reproduced? |")
    w("|---|---|---|---|---|---|---|---|")
    for s in sorted(set(rec) | set(new)):
        if s in rec and s in new:
            dc = abs(rec[s]['cross_subject_mae'] - new[s]['cross_subject_mae'])
            df = abs(rec[s]['calib_full_mae'] - new[s]['calib_full_mae'])
            ok = "yes" if (dc <= 0.05 and df <= 0.05) else "**NO**"
            w(f"| {s} | {rec[s]['cross_subject_mae']:.3f} | {new[s]['cross_subject_mae']:.3f} | {dc:.3f} | "
              f"{rec[s]['calib_full_mae']:.3f} | {new[s]['calib_full_mae']:.3f} | {df:.3f} | {ok} |")
        else:
            side = "recorded-only" if s in rec else "new-only (p05–p14 had no prior record)"
            w(f"| {s} | — | — | — | — | — | — | {side} |")
else:
    w("_Step 3 output or recorded reference missing — see logs/step3_lopo_backbone.log._")
w("")

# ---- item 6: detector ----
w("## 6. Detector mean ROC-AUC vs expected 0.9512 (Step 4)")
detp = os.path.join(AG, 'experiments', 'detector_lopo', 'results_overnight_20260808.json')
if os.path.exists(detp):
    d = json.load(open(detp))
    rocs = [r['det_roc'] for r in d if 'det_roc' in r]
    if rocs:
        m = float(np.mean(rocs)); sd = float(np.std(rocs, ddof=1))
        ci = 1.96 * sd / np.sqrt(len(rocs))
        w(f"Folds: {len(rocs)}.  Mean det ROC-AUC = **{m:.4f}** ± {ci:.4f} (95%).  Expected 0.9512.  "
          f"|Δ| = {abs(m-0.9512):.4f} → {'reproduces' if abs(m-0.9512)<=0.01 else 'DIFFERS'}.")
    else:
        w("_No det_roc entries in detector results._")
else:
    w("_Step 4 output missing — detector_lopo.py has no torch.save, so per-fold weights were NOT persisted "
      "(reported per instructions; code not edited). See logs/step4_detector_lopo.log._")
w("")

# ---- item 7: wall times ----
w("## 7. Wall time per step")
ts = os.path.join(LOGS, 'timings.tsv')
if os.path.exists(ts):
    w("| step | duration |"); w("|---|---|")
    for line in open(ts):
        parts = line.strip().split('\t')
        if len(parts) == 3:
            name, s0, s1 = parts
            try: w(f"| {name} | {sec_to_hms(float(s1)-float(s0))} |")
            except Exception: pass
else:
    w("_No timings recorded._")
w("")
w("---")
w("_Reproducibility note: run_phase1 seeds corruption via `hash((sid,model,delta,pc))`, which Python salts "
  "per process, so absolute per-cell AUCs vary slightly across separate runs; the CIs above capture "
  "within-run frame sampling, not that cross-process draw variance. Trends (floor location, ordering) are stable._")

report = os.path.join(LOGS, 'MONDAY_REPORT.md')
open(report, 'w').write("\n".join(L) + "\n")
print("wrote", report)
