#!/usr/bin/env python3
# make_transport_tables.py -- generated tables for the cross-corpus section.
"""Sibling of make_tables.py for everything that spans two corpora.

Kept separate because make_tables.py is scoped to MPIIFaceGaze's SUBJ throughout;
threading a second corpus through it would touch every existing table for the
sake of three new ones.

It follows make_tables.py's rule: nothing here reads a summary JSON that some
earlier CLI invocation may have overwritten. Every number is RECOMPUTED from the
cached features, by importing the same functions the experiment scripts use, so
a table and the experiment it reports cannot diverge.

The RT-GENE subject list is read from the build's participants.json, so the
tables use PARTICIPANTS and not sessions without that having to be remembered at
the call site. s014/s015 repeat s002/s005 (Zenodo doi 10.5281/zenodo.2529036).

Usage:  python3 make_transport_tables.py --table {1,2,3,all}
  1  transport of c(kappa), both corpora, with CIs        (~1 min)
  2  coherence x locality interaction, both corpora       (~2 min)
  3  per-frame detection floor by scorer, both corpora    (~1 min)
"""
import argparse, json, os, sys
import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import gaze_math as gm                                  # noqa: E402
import corruption_temporal as ct                        # noqa: E402
import exp_coherence as E                               # noqa: E402
import exp_prior_tiebreak as PT                         # noqa: E402
import exp_transport_ci as TC                           # noqa: E402
import exp_interaction_ci as IC                         # noqa: E402
import exp_identifiability as ID                        # noqa: E402
from exp_transport import load, PC, SEEDS               # noqa: E402
from exp_prior_detector import resub_functional         # noqa: E402

TDIR = os.path.join(_HERE, "manuscript_coherence", "tables")
LAM, K, B = 1e-2, 9, 2000
FEAT_A, LABEL_A = "unigaze_features", "MPIIFaceGaze"
FEAT_B, LABEL_B = "rtgene_unigaze_features", "RT-GENE"
LABEL_C, FEAT_C = "EYEDIAP", "eyediap_unigaze_features"
SUBJ_A = [f"p{i:02d}" for i in range(15)]
# The 14 EYEDIAP participants with screen sessions, frozen in PREREG_eyediap.md
# section 2 rule 1. e12/e13 are floating-target only and have no CS session.
SUBJ_C = "e01,e02,e03,e04,e05,e06,e07,e08,e09,e10,e11,e14,e15,e16".split(",")

# MPIIFaceGaze is the reference throughout: it is the corpus the published
# constant was measured on, so every ratio is read against it rather than against
# a pooled mean, which would hide which corpus moved.
def corpora():
    return [(LABEL_A, FEAT_A, SUBJ_A),
            (LABEL_B, FEAT_B, subj_b()),
            (LABEL_C, FEAT_C, SUBJ_C)]
# The interaction's clustered kappa=1 cell on RT-GENE lands near the top of the
# standard grid; without these the crossing is censored in half the bootstrap
# replicates and every CI is computed on an outcome-selected subset.
GRID_EXT = [60, 70, 80, 90, 100, 120, 150]


def subj_b():
    p = os.path.join(_HERE, "..", "data", "RTGENE_Normalized", "participants.json")
    if not os.path.exists(p):
        sys.exit(f"ABORT: {p} missing -- run prepare_rtgene_labels.py first.")
    return json.load(open(p))["unique_participants"]


def w(name, body):
    os.makedirs(TDIR, exist_ok=True)
    with open(os.path.join(TDIR, name), "w") as fh:
        fh.write(body)
    print(f"  wrote tables/{name}")


SLUG = {LABEL_A: "mpii", LABEL_B: "rtgene", LABEL_C: "eyediap"}


def slug(label):
    """Filename stem per corpus. A two-way 'mpii else rtgene' test silently gave
    EYEDIAP RT-GENE's filenames and overwrote its values the moment a third corpus
    was added, so the mapping is explicit and fails loudly on an unknown label."""
    if label not in SLUG:
        raise KeyError(f"no filename slug for corpus {label!r}; add it to SLUG")
    return SLUG[label]


def ci_str(ci, fmt="{:.2f}"):
    return "--" if not ci else f"[${fmt.format(ci[0])}$, ${fmt.format(ci[1])}$]"


# ---------------------------------------------------------------- table 1
def table1():
    """c(kappa) in both corpora, with subject-bootstrap CIs and their ratio."""
    rng = np.random.default_rng(0)
    arms = {}
    for label, feat, subj in corpora():
        feats = load(feat, subj)
        clean, cells = TC.precompute(feats, subj)
        e0, pt = TC.one_replicate(subj, clean, cells)
        reps = [TC.one_replicate([subj[i] for i in rng.integers(0, len(subj), len(subj))],
                                 clean, cells) for _ in range(B)]
        arms[label] = {"e": e0, "pt": pt, "reps": reps, "n": len(subj)}

    b = ["% generated by make_transport_tables.py -- do not edit",
         r"\begin{tabular}{ll" + "c" * len(E.KAPPAS) + "}", r"\toprule",
         r"Corpus & & " + " & ".join(rf"$\kappa={k:g}$" for k in E.KAPPAS) + r" \\",
         r"\midrule"]
    for label, _, _ in corpora():
        a = arms[label]
        b.append(rf"{label} ($n={a['n']}$, $\hat{{e}}={a['e']:.2f}$\dg) & $c$ & " +
                 " & ".join(f"{a['pt'][k][1]:.3f}" if a["pt"][k][1] else "--"
                            for k in E.KAPPAS) + r" \\")
        b.append(r" & $95\%$ CI & " + " & ".join(
            ci_str(TC.pct([r[1][k][1] for r in a["reps"]]), "{:.2f}")
            for k in E.KAPPAS) + r" \\")
    # Each non-reference corpus is ratioed against MPIIFaceGaze, replicate by
    # replicate. With three corpora a pooled ratio would hide WHICH corpus moved,
    # and a full pairwise matrix would trade that for a table nobody reads.
    all_r = {}
    for label, _, _ in corpora()[1:]:
        b.append(r"\midrule")
        ratios = {}
        for k in E.KAPPAS:
            ca, cb = arms[LABEL_A]["pt"][k][1], arms[label]["pt"][k][1]
            rs = [rb[1][k][1] / ra[1][k][1]
                  for ra, rb in zip(arms[LABEL_A]["reps"], arms[label]["reps"])
                  if ra[1][k][1] and rb[1][k][1]]
            ratios[k] = (cb / ca if (ca and cb) else None, TC.pct(rs))
        b.append(f"Ratio to {LABEL_A} & & " +
                 " & ".join(f"{ratios[k][0]:.3f}" if ratios[k][0] else "--"
                            for k in E.KAPPAS) + r" \\")
        b.append(rf"\quad ({label}) & $95\%$ CI & " +
                 " & ".join(ci_str(ratios[k][1]) for k in E.KAPPAS) + r" \\")
        all_r[label] = ratios
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_transport.tex", "\n".join(b) + "\n")

    flat = [r[0] for rr in all_r.values() for r in rr.values() if r[0]]
    lo, hi = min(flat), max(flat)
    w("val_transport_ratio_lo.tex", f"{lo:.2f}")
    w("val_transport_ratio_hi.tex", f"{hi:.2f}")
    w("val_ehat_rtgene.tex", f"{arms[LABEL_B]['e']:.2f}")
    w("val_n_rtgene.tex", f"{arms[LABEL_B]['n']}")
    w("val_ehat_eyediap.tex", f"{arms[LABEL_C]['e']:.2f}")
    w("val_n_eyediap.tex", f"{arms[LABEL_C]['n']}")
    w("val_c0_eyediap.tex", f"{arms[LABEL_C]['pt'][E.KAPPAS[0]][1]:.3f}")
    ehats = sorted(a["e"] for a in arms.values())
    w("val_ehat_span.tex", f"{ehats[-1]/ehats[0]:.1f}")
    contains = all(r[1] and r[1][0] <= 1 <= r[1][1]
                   for rr in all_r.values() for r in rr.values())
    print(f"    ratios span {lo:.3f}--{hi:.3f}; every CI "
          f"{'contains' if contains else 'DOES NOT contain'} 1")
    print(f"    ehat spans {ehats[0]:.2f}--{ehats[-1]:.2f} deg ({ehats[-1]/ehats[0]:.1f}x)")


# ---------------------------------------------------------------- table 2
def table2(only=None):
    """The 2x2 interaction, both corpora, paired bootstrap, extended grid."""
    IC.GRID = sorted(set(IC.GRID) | {float(x) for x in GRID_EXT})
    print(f"  grid top {max(IC.GRID):g}")
    arms = {}
    for label, feat, subj in corpora():
        # Per-corpus cache. Three corpora over two localities and the extended grid
        # is ~3 minutes of precompute, which exceeds a single interactive call, so
        # each corpus is computed once and reused. Cache is keyed by the things
        # that change the numbers; a protocol edit invalidates it rather than
        # silently mixing an old arm with a new one.
        key = f"{feat}|{','.join(subj)}|{LAM}|{B}|{max(IC.GRID):g}|{len(IC.GRID)}"
        cf = os.path.join(_HERE, "_transport_cache",
                          f"interaction_{slug(label)}.json")
        os.makedirs(os.path.dirname(cf), exist_ok=True)
        if os.path.exists(cf):
            c = json.load(open(cf))
            if c.get("key") == key:
                arms[label] = {"pt": c["pt"], "reps": c["reps"], "n": len(subj),
                               "cens": c["cens"]}
                print(f"  {label}: cached")
                continue
            print(f"  {label}: cache stale (protocol changed), recomputing")
        # One subject draw per replicate, seeded per corpus so a corpus computed
        # alone gets the same draws as one computed in a batch.
        rng = np.random.default_rng(0)
        cells = IC.precompute(load(feat, subj), subj, LAM)
        pt = IC.floors_for(subj, cells)
        reps = [IC.floors_for([subj[i] for i in rng.integers(0, len(subj), len(subj))],
                              cells) for _ in range(B)]
        stats = [IC.stats_from(r) for r in reps]
        # Censoring is counted on the STATS, not on the raw floors dicts: those are
        # keyed by (locality, kappa) tuples and have no "interaction" key at all,
        # so testing them reports 100% censored regardless of the data.
        cens = sum(1 for x in stats if "interaction" not in x)
        arms[label] = {"pt": IC.stats_from(pt), "reps": stats, "n": len(subj),
                       "cens": cens}
        json.dump({"key": key, "pt": arms[label]["pt"], "reps": stats, "cens": cens},
                  open(cf, "w"))
        print(f"  {label}: computed and cached")
        if only:
            continue

    # The floor is the first crossing of an ROC curve, sustained to the grid top:
    # a highly non-smooth functional of a POOLED statistic. Resampling subjects can
    # therefore move it a long way, and the percentile bootstrap is not well
    # centred on the full-sample value -- on EYEDIAP the interaction point estimate
    # sits near the top of its own bootstrap distribution. The median is emitted
    # beside the point so the skew is visible rather than implied, and the worst
    # divergence is emitted as a value the text must quote.
    labels = [c[0] for c in corpora()]
    skew = {}
    for label in labels:
        a = arms[label]
        for key in ("interaction", "lapse_ratio"):
            v = [r[key] for r in a["reps"] if key in r]
            pt = a["pt"].get(key)
            if v and pt is not None:
                import numpy as _np
                skew[(label, key)] = (pt, float(_np.median(v)),
                                      float((_np.asarray(v) < pt).mean() * 100))
    if skew:
        worst = max(skew.items(), key=lambda kv: kv[1][2])
        w("val_interaction_pct.tex", f"{worst[1][2]:.0f}")
        w("val_interaction_median.tex", f"{worst[1][1]:.2f}")
        w("val_interaction_point.tex", f"{worst[1][0]:.2f}")
        w("val_interaction_skew_corpus.tex", worst[0][0])
        print("    point-vs-bootstrap-median (skew check):")
        for (lab, key), (pt, med, pc) in sorted(skew.items()):
            flag = "   <-- poorly centred" if pc > 80 or pc < 20 else ""
            print(f"      {lab:<13} {key:<13} point {pt:>7.2f}  median {med:>7.2f}  "
                  f"point at {pc:>5.1f}th pct{flag}")

    names = [("coherence_main", r"Coherence main effect (\dg)", "{:+.2f}"),
             ("locality_main", r"Locality main effect (\dg)", "{:+.2f}"),
             ("interaction", r"Interaction (\dg)", "{:+.2f}"),
             ("lapse_ratio", r"Lapse ratio", "{:.2f}")]
    b = ["% generated by make_transport_tables.py -- do not edit",
         r"\begin{tabular}{l" + "cc" * len(labels) + "}", r"\toprule",
         "Statistic & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{L}}}" for L in labels)
         + r" \\",
         "".join(rf"\cmidrule(lr){{{2+2*i}-{3+2*i}}}" for i in range(len(labels))),
         " & " + " & ".join(r"value & $95\%$ CI" for _ in labels) + r" \\",
         r"\midrule"]
    for key, disp, fmt in names:
        row = [disp]
        for label in labels:
            a = arms[label]
            v = a["pt"].get(key)
            vals = [s[key] for s in a["reps"] if key in s]
            row += [f"${fmt.format(v)}$" if v is not None else "--",
                    ci_str(TC.pct(vals), "{:.2f}")]
        b.append(" & ".join(row) + r" \\")
        if key in ("interaction", "lapse_ratio"):
            mrow = [r"\quad bootstrap median"]
            for label in labels:
                m = skew.get((label, key))
                mrow += [f"${m[1]:.2f}$" if m else "--", ""]
            b.append(" & ".join(mrow) + r" \\")
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_interaction.tex", "\n".join(b) + "\n")
    for label in labels:
        a = arms[label]
        print(f"    {label}: {a['cens']}/{B} replicates censored "
              f"({a['cens']/B:.0%})")
        w(f"val_censored_pct_{slug(label)}.tex", f"{a['cens']/B*100:.0f}")
    w("val_rtgene_censored_pct.tex", f"{arms[LABEL_B]['cens']/B*100:.0f}")


# ---------------------------------------------------------------- table 3
def table3():
    """Per-frame detection floor by scorer, both corpora."""
    b = ["% generated by make_transport_tables.py -- do not edit",
         r"\begin{tabular}{ll" + "c" * len(E.KAPPAS) + "}", r"\toprule",
         r"Corpus & Scorer & " + " & ".join(rf"$\kappa={k:g}$" for k in E.KAPPAS)
         + r" \\", r"\midrule"]
    vals = {}
    for label, feat, subj in corpora():
        W, full = PT.population_maps(1.0, feat_dir=os.path.join(_HERE, feat),
                                     subjects=subj)
        feats = {s: (full[s][0][:K], full[s][1][:K]) for s in subj}
        loo_f = {s: E.loo_functionals(feats[s][0], LAM) for s in subj}
        res_f = {s: resub_functional(feats[s][0], LAM) for s in subj}
        pop = {s: PT.predict(W[s], feats[s][0]) for s in subj}
        xerr = float(np.mean([np.mean(gm.angular_error_deg(
            PT.predict(W[s], full[s][0]), full[s][1])) for s in subj]))
        first = True
        for sc, disp in (("resub", "Resubstitution"), ("loo", "Leave-one-out"),
                         ("prior", "Population prior")):
            fl = []
            for kap in E.KAPPAS:
                aucs = []
                for d in IC.GRID:
                    v, p = [], []
                    for s in subj:
                        for sd in range(SEEDS):
                            c = ct.apply_coherent(feats[s][1], s, d, PC, sd, kap,
                                                  locality="clustered")
                            Yc = c["corrupted_labels"]
                            r = (gm.angular_error_deg(res_f[s] @ Yc, Yc) if sc == "resub"
                                 else gm.angular_error_deg(Yc, pop[s]) if sc == "prior"
                                 else E.loo_resid(loo_f[s], Yc))
                            v.extend(np.atleast_1d(r).tolist())
                            p.extend(c["is_corrupted"].tolist())
                    aucs.append(TC.auc_fast(np.asarray(v), np.asarray(p, bool)))
                fl.append(E.crossing(IC.GRID, aucs, 0.7)[0])
            head = (rf"{label} ($\bar{{e}}_{{\mathrm{{x}}}}={xerr:.2f}$\dg)"
                    if first else "")
            first = False
            b.append(f"{head} & {disp} & " +
                     " & ".join(f"{x:.2f}" if x else "none" for x in fl) + r" \\")
            vals[(label, sc)] = fl
        if label != corpora()[-1][0]:
            b.append(r"\midrule")
        w(f"val_xsubj_mae_{slug(label)}.tex", f"{xerr:.2f}")
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_prior_transport.tex", "\n".join(b) + "\n")
    for label, _, _ in corpora():
        f = vals[(label, "prior")]
        if f[0] and f[-1]:
            print(f"    {label} prior drift k=1 minus k=0: {f[-1]-f[0]:+.2f} deg")
            w(f"val_prior_drift_{slug(label)}.tex",
              f"{f[-1]-f[0]:+.2f}")


# ---------------------------------------------------------------- table 4
def table4():
    """Identifiability index on both corpora.

    Severities are SCALED between corpora. I asks whether the corrupted subset is
    as self-consistent as the clean one, and a fixed delta is a different fraction
    of ehat in each corpus -- RT-GENE's is 1.68x MPIIFaceGaze's -- so quoting both
    at the same absolute delta compares different relative regimes. The MPIIFaceGaze
    severities are the paper's own; the RT-GENE ones are those multiplied by that
    ratio and rounded.

    Cell counts are reported because both subsets need >= 3 frames for a
    leave-one-out fit: at p_c=0.2 a nine-frame support usually yields only about
    two corrupted frames, so most cells are skipped and that row rests on far less
    data than the p_c=0.4 row. Omitting the count would hide it."""
    # Clean-fit ehat per corpus, read from table 1's emitted values so the scaling
    # cannot drift from the transport table it is scaled against.
    def _v(n):
        return float(open(os.path.join(TDIR, n)).read().strip())
    EHAT = {LABEL_A: 6.15, LABEL_B: _v("val_ehat_rtgene.tex"),
            LABEL_C: _v("val_ehat_eyediap.tex")}
    ds_a = [6, 10, 16, 20]
    DS = {L: [round(d * EHAT[L] / EHAT[LABEL_A]) for d in ds_a] for L in EHAT}
    for L in EHAT:
        print(f"  severities  {L:<13} {DS[L]}  (ehat {EHAT[L]:.2f}, "
              f"x{EHAT[L]/EHAT[LABEL_A]:.2f})")

    b = ["% generated by make_transport_tables.py -- do not edit",
         r"\begin{tabular}{llc" + "c" * len(E.KAPPAS) + "}", r"\toprule",
         r"Corpus & $p_c$ & $\delta$ (\dg) & " +
         " & ".join(rf"$\kappa={k:g}$" for k in E.KAPPAS) + r" \\", r"\midrule"]
    for label, feat, subj in corpora():
        ds = DS[label]
        feats = E.load_feats("unigaze", "L0", feat_dir=os.path.join(_HERE, feat),
                             subjects=subj)
        first = True
        for pc in (0.2, 0.4):
            for d in ds:
                cells, used = [], 0
                for kap in E.KAPPAS:
                    rs = []
                    for s in subj:
                        F, Y = feats[s]
                        for seed in range(SEEDS):
                            c = ct.apply_coherent(Y, s, d, pc, seed, kap,
                                                  locality="clustered")
                            m = c["is_corrupted"]
                            wc = ID.within(F[~m], Y[~m], LAM)
                            wx = ID.within(F[m], c["corrupted_labels"][m], LAM)
                            if wc and wx and wc > 0:
                                rs.append(wx / wc)
                    cells.append(np.mean(rs) if rs else None)
                    used = max(used, len(rs))
                head = label if first else ""
                first = False
                b.append(f"{head} & {pc} & {d} & " +
                         " & ".join(f"{x:.2f}" if x else "--" for x in cells) + r" \\")
            if pc == 0.2:
                b.append(r"\addlinespace")
        if label != corpora()[-1][0]:
            b.append(r"\midrule")
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_identifiability_transport.tex", "\n".join(b) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", default="all", choices=("1", "2", "3", "4", "all"))
    ap.add_argument("--only", default=None,
                    help="table 2 only: compute this corpus's cache and stop. Three "
                         "corpora exceed one interactive call; run once per corpus, "
                         "then again with no --only to assemble the table.")
    a = ap.parse_args()
    for t, fn in (("1", table1), ("2", table2), ("3", table3), ("4", table4)):
        if a.table in (t, "all"):
            print(f"table {t}:")
            fn(a.only) if t == "2" else fn()
    return 0


if __name__ == "__main__":
    sys.exit(main())
