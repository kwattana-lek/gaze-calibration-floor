#!/usr/bin/env python3
# make_tables.py -- regenerate every number in the coherence manuscript.
"""Single source of truth for the manuscript's tables.

Each table is recomputed from the cached features and the corruption models; no
table reads a records file that some earlier CLI invocation may have overwritten.
Emits LaTeX fragments into manuscript_coherence/tables/ which main.tex \\input's,
so the manuscript cannot drift from the code.

Usage:  python3 make_tables.py --table {1,2,3,4,5,all}
"""
import argparse, os, sys
import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import gaze_math as gm                              # noqa: E402
import corruption_temporal as ct                    # noqa: E402
import exp_coherence as E                           # noqa: E402
import exp_prior_tiebreak as PT                     # noqa: E402
import exp_identifiability as ID                    # noqa: E402
from exp_prior_detector import resub_functional     # noqa: E402
from unigaze_arm import SUBJ, K, roc_auc            # noqa: E402

TDIR = os.path.join(_HERE, "manuscript_coherence", "tables")
LAM, PC, SEEDS = 1e-2, 0.2, 10
GRID = E.DELTAS_BASE + E.DELTAS_EXT
ARMS = [("resnet", "L0", "ResNet-18 L0"), ("resnet", "L1", "ResNet-18 L1"),
        ("resnet", "L2", "ResNet-18 L2"), ("unigaze", None, "UniGaze ViT-H/14")]


def w(name, body):
    os.makedirs(TDIR, exist_ok=True)
    with open(os.path.join(TDIR, name), "w") as fh:
        fh.write(body)
    print(f"  wrote tables/{name}")


def floor_for(feats, funcs, kap, pc, loc, scorer=None, res_f=None, pop=None):
    aucs = []
    for d in GRID:
        v, p = [], []
        for s in SUBJ:
            F, Y = feats[s]
            for seed in range(SEEDS):
                c = ct.apply_coherent(Y, s, d, pc, seed, kap, locality=loc)
                Yc = c["corrupted_labels"]
                if scorer == "resub":
                    r = gm.angular_error_deg(res_f[s] @ Yc, Yc)
                elif scorer == "prior":
                    r = gm.angular_error_deg(Yc, pop[s])
                else:
                    r = E.loo_resid(funcs[s], Yc)
                v.extend(np.atleast_1d(r).tolist())
                p.extend(c["is_corrupted"].tolist())
        aucs.append(roc_auc(v, p))
    return E.crossing(GRID, aucs, 0.7)[0]


def table1(feats, funcs):
    """Locality x coherence, UniGaze frozen. Also emits the lapse ratio and its CI.

    The ratio floor(clustered, kappa=1) / floor(scattered, kappa=0) is quoted in
    the abstract and in Section 6.3, and until now it was HAND-TYPED with no
    generator -- which is how it came to read 2.07 while this table's own cells
    give 16.72/7.60 = 2.20. It is emitted as a \input value here so the prose
    cannot disagree with the table above it again."""
    rows = {}
    for loc in ("scattered", "clustered"):
        rows[loc] = [floor_for(feats, funcs, k, PC, loc) for k in E.KAPPAS]
    _lapse_ratio(feats, funcs, rows)
    b = ["% generated by make_tables.py -- do not edit",
         r"\begin{tabular}{l" + "c" * len(E.KAPPAS) + "}", r"\toprule",
         "Locality & " + " & ".join(rf"$\kappa={k:g}$" for k in E.KAPPAS) + r" \\",
         r"\midrule"]
    for loc in ("scattered", "clustered"):
        b.append(loc.capitalize() + " & " +
                 " & ".join(f"{x:.2f}" if x else "--" for x in rows[loc]) + r" \\")
    d = [rows["clustered"][i] - rows["scattered"][i] for i in range(len(E.KAPPAS))]
    b += [r"\midrule", "Difference & " + " & ".join(f"${x:+.2f}$" for x in d) + r" \\",
          r"\bottomrule", r"\end{tabular}"]
    w("tab_locality.tex", "\n".join(b) + "\n")


def _lapse_ratio(feats, funcs, rows, B=2000, seed=0):
    """Lapse ratio with a subject-level bootstrap CI, paired within each replicate."""
    base, lapse = rows["scattered"][0], rows["clustered"][-1]
    if not (base and lapse):
        return
    k0, k1 = E.KAPPAS[0], E.KAPPAS[-1]
    cells = {}
    for loc, kap in (("scattered", k0), ("clustered", k1)):
        for d in GRID:
            sc, lb = {}, {}
            for s in SUBJ:
                v, p = [], []
                for sd in range(SEEDS):
                    c = ct.apply_coherent(feats[s][1], s, d, PC, sd, kap, locality=loc)
                    v.extend(np.atleast_1d(
                        E.loo_resid(funcs[s], c["corrupted_labels"])).tolist())
                    p.extend(c["is_corrupted"].tolist())
                sc[s], lb[s] = np.asarray(v, float), np.asarray(p, bool)
            cells[(loc, kap, d)] = (sc, lb)

    def fl(draw, loc, kap):
        a = [roc_auc(np.concatenate([cells[(loc, kap, d)][0][s] for s in draw]),
                     np.concatenate([cells[(loc, kap, d)][1][s] for s in draw]))
             for d in GRID]
        return E.crossing(GRID, a, 0.7)[0]

    rs = np.random.default_rng(seed)
    vals = []
    for _ in range(B):
        # ONE draw per replicate: the ratio is a within-subject contrast.
        dr = [SUBJ[i] for i in rs.integers(0, len(SUBJ), len(SUBJ))]
        a, b = fl(dr, "scattered", k0), fl(dr, "clustered", k1)
        if a and b:
            vals.append(b / a)
    lo, hi = np.percentile(vals, [2.5, 97.5])
    # Three separate scalars, each usable inside $...$, matching val_xsubj_mae's
    # convention. A single file carrying its own $ signs would nest math mode.
    w("val_lapse_ratio.tex", f"{lapse/base:.2f}")
    w("val_lapse_ratio_lo.tex", f"{lo:.2f}")
    w("val_lapse_ratio_hi.tex", f"{hi:.2f}")
    # The lambda-stability list quoted alongside the ratio was the last hand-typed
    # set of numbers in the manuscript -- the same hazard that let 2.07 stand.
    rs_lam = []
    for lm in (1e-3, 1e-2, 1e-1, 1.0):
        fu = {t: E.loo_functionals(feats[t][0], lm) for t in SUBJ}
        b0 = floor_for(feats, fu, E.KAPPAS[0], PC, "scattered")
        b1 = floor_for(feats, fu, E.KAPPAS[-1], PC, "clustered")
        rs_lam.append(b1 / b0 if (b0 and b1) else None)
    w("val_lapse_ratio_lams.tex",
      ", ".join(f"${x:.2f}$" if x else "--" for x in rs_lam))
    print("    lambda stability: " +
          ", ".join(f"{x:.3f}" if x else "--" for x in rs_lam))
    print(f"    lapse ratio {lapse/base:.3f}  median {np.median(vals):.3f}  "
          f"95% CI [{lo:.3f}, {hi:.3f}]  ({len(vals)}/{B} usable)")


def table2():
    """c as a function of kappa, four arms, clean-fit ehat."""
    b = ["% generated by make_tables.py -- do not edit",
         r"\begin{tabular}{lc" + "c" * len(E.KAPPAS) + "}", r"\toprule",
         r"Configuration & $\hat{e}$ (\dg) & " +
         " & ".join(rf"$\kappa={k:g}$" for k in E.KAPPAS) + r" \\", r"\midrule"]
    allc = {k: [] for k in E.KAPPAS}
    for arm, lvl, name in ARMS:
        fe = E.load_feats(arm, lvl or "L0")
        fu = {s: E.loo_functionals(fe[s][0], LAM) for s in SUBJ}
        eh = float(np.mean([np.mean(E.loo_resid(fu[s], fe[s][1])) for s in SUBJ]))
        cs = []
        for k in E.KAPPAS:
            fl = floor_for(fe, fu, k, PC, "scattered")
            cs.append(fl / eh if fl else None)
            if fl:
                allc[k].append(fl / eh)
        b.append(f"{name} & {eh:.2f} & " +
                 " & ".join(f"{x:.3f}" if x else "--" for x in cs) + r" \\")
    b.append(r"\midrule")
    b.append("Mean & & " + " & ".join(f"{np.mean(allc[k]):.3f}" for k in E.KAPPAS) + r" \\")
    b.append("CV & & " + " & ".join(
        f"{np.std(allc[k])/np.mean(allc[k]):.3f}" for k in E.KAPPAS) + r" \\")
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_c_vs_kappa.tex", "\n".join(b) + "\n")


def table3(feats, funcs):
    """Mechanism: residual split by frame status."""
    b = ["% generated by make_tables.py -- do not edit",
         r"\begin{tabular}{ccccc}", r"\toprule",
         r"$\delta$ (\dg) & $\kappa$ & Clean & Corrupted & Gap \\", r"\midrule"]
    for d in (6, 10, 16):
        for kap in (0.0, 0.5, 1.0):
            cl, co = [], []
            for s in SUBJ:
                F, Y = feats[s]
                for seed in range(SEEDS):
                    c = ct.apply_coherent(Y, s, d, PC, seed, kap)
                    r = E.loo_resid(funcs[s], c["corrupted_labels"])
                    m = c["is_corrupted"]
                    cl.extend(r[~m].tolist()); co.extend(r[m].tolist())
            cl, co = np.mean(cl), np.mean(co)
            b.append(f"{d} & {kap:g} & {cl:.2f} & {co:.2f} & {co-cl:.2f}" + r" \\")
        if d != 16:
            b.append(r"\addlinespace")
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_mechanism.tex", "\n".join(b) + "\n")


def table4(feats):
    """Identifiability index."""
    b = ["% generated by make_tables.py -- do not edit",
         r"\begin{tabular}{cc" + "c" * len(E.KAPPAS) + "}", r"\toprule",
         r"$p_c$ & $\delta$ (\dg) & " +
         " & ".join(rf"$\kappa={k:g}$" for k in E.KAPPAS) + r" \\", r"\midrule"]
    for pc in (0.2, 0.4):
        for d in (6, 10, 16, 20):
            cells = []
            for kap in E.KAPPAS:
                rs = []
                for s in SUBJ:
                    F, Y = feats[s]
                    for seed in range(SEEDS):
                        c = ct.apply_coherent(Y, s, d, pc, seed, kap,
                                              locality="clustered")
                        m = c["is_corrupted"]
                        wc = ID.within(F[~m], Y[~m], LAM)
                        wx = ID.within(F[m], c["corrupted_labels"][m], LAM)
                        if wc and wx and wc > 0:
                            rs.append(wx / wc)
                cells.append(np.mean(rs) if rs else None)
            b.append(f"{pc} & {d} & " +
                     " & ".join(f"{x:.2f}" if x else "--" for x in cells) + r" \\")
        if pc == 0.2:
            b.append(r"\addlinespace")
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_identifiability.tex", "\n".join(b) + "\n")


def table5(feats, funcs):
    """Per-frame detector floors: resub / loo / prior."""
    W, full = PT.population_maps(1.0)
    res_f = {s: resub_functional(feats[s][0], LAM) for s in SUBJ}
    pop = {s: PT.predict(W[s], feats[s][0]) for s in SUBJ}
    xerr = float(np.mean([np.mean(gm.angular_error_deg(PT.predict(W[s], full[s][0]),
                                                       full[s][1])) for s in SUBJ]))
    b = ["% generated by make_tables.py -- do not edit",
         f"% leave-one-subject-out population map cross-subject MAE: {xerr:.2f} deg",
         r"\begin{tabular}{ll" + "c" * len(E.KAPPAS) + "c}", r"\toprule",
         r"$p_c$ & Scorer & " + " & ".join(rf"$\kappa={k:g}$" for k in E.KAPPAS)
         + r" & Spread \\", r"\midrule"]
    for pc in (0.2, 0.4):
        for sc in ("resub", "loo", "prior"):
            vals = [floor_for(feats, funcs, k, pc, "clustered", scorer=sc,
                              res_f=res_f, pop=pop) for k in E.KAPPAS]
            ok = [x for x in vals if x]
            sp = f"${max(ok)-min(ok):+.2f}$" if len(ok) == len(vals) else "--"
            lab = {"resub": "Resubstitution", "loo": "Leave-one-out",
                   "prior": "Population prior"}[sc]
            b.append((f"{pc} & " if sc == "resub" else " & ") + lab + " & " +
                     " & ".join(f"{v:.2f}" if v else r"\emph{none}" for v in vals)
                     + f" & {sp}" + r" \\")
        if pc == 0.2:
            b.append(r"\addlinespace")
    b += [r"\bottomrule", r"\end{tabular}"]
    w("tab_detector.tex", "\n".join(b) + "\n")
    w("val_xsubj_mae.tex", f"{xerr:.2f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", default="all")
    a = ap.parse_args()
    feats = E.load_feats("unigaze", "L0")
    funcs = {s: E.loo_functionals(feats[s][0], LAM) for s in SUBJ}
    t = a.table
    if t in ("1", "all"): table1(feats, funcs)
    if t in ("3", "all"): table3(feats, funcs)
    if t in ("4", "all"): table4(feats)
    if t in ("5", "all"): table5(feats, funcs)
    if t in ("2", "all"): table2()
    return 0


if __name__ == "__main__":
    sys.exit(main())
